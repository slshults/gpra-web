def upgrade():
    """Insert curated chord pool. No-op if chord_pool already has rows.

    INNER JOIN LATERAL filters out names that have no matching common_chords
    row, so every inserted entry has a valid common_chord_id.
    """
    op.execute(f"""
        INSERT INTO chord_pool (chord_name, common_chord_id, display_order)
        SELECT cn.chord_name, resolved.id, cn.display_order
        FROM (VALUES {CHORD_POOL_VALUES}) AS cn(chord_name, display_order)
        INNER JOIN LATERAL (
            SELECT id FROM common_chords
            WHERE LOWER(name) = LOWER(cn.chord_name)
            ORDER BY order_col NULLS LAST, id
            LIMIT 1
        ) AS resolved ON true
        WHERE NOT EXISTS (SELECT 1 FROM chord_pool LIMIT 1);
    """)


def downgrade():
    """Remove all chord_pool rows seeded by this migration.

    NOTE: this CASCADE-deletes posted_chords rows due to FK ON DELETE CASCADE.
    Only safe to downgrade if you're OK losing post audit history. PostHog
    events are unaffected.
    """
    op.execute("DELETE FROM chord_pool;")
